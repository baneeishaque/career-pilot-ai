from pydantic import BaseModel, Field, BeforeValidator
from typing import List, Optional, Annotated

def clean_string(v):
    """
    Strips leading and trailing whitespace from string inputs.
    """
    if isinstance(v, str):
        return v.strip()
    return v

def coerce_to_list(v):
    """
    Coerces None/null inputs to an empty list to prevent validation crashes.
    """
    return v if v is not None else []

# Type alias for auto-cleaned strings
CleanStr = Annotated[str, BeforeValidator(clean_string)]


class WorkExperience(BaseModel):
    """
    Represents a chronological work experience timeline entry for a candidate.
    """
    company: Optional[CleanStr] = Field(
        default=None, 
        description="Name of the company or organization."
    )
    title: Optional[CleanStr] = Field(
        default=None, 
        description="The role or title held by the candidate."
    )
    start_date: Optional[CleanStr] = Field(
        default=None, 
        description="Start date of employment (e.g., 'YYYY-MM' or 'Month YYYY')."
    )
    end_date: Optional[CleanStr] = Field(
        default=None, 
        description="End date of employment, or null/Present if currently working there."
    )
    description: Optional[CleanStr] = Field(
        default=None, 
        description="Summary of key tasks, responsibilities, and achievements."
    )


class EducationEntry(BaseModel):
    """
    Represents an academic credential/qualification for a candidate.
    """
    institution: Optional[CleanStr] = Field(
        default=None, 
        description="Name of the academic institution."
    )
    degree: Optional[CleanStr] = Field(
        default=None, 
        description="The type of degree earned (e.g., 'BS', 'MS', 'PhD')."
    )
    field_of_study: Optional[CleanStr] = Field(
        default=None, 
        description="Major, concentration, or specialization field."
    )
    graduation_date: Optional[CleanStr] = Field(
        default=None, 
        description="Graduation year or date, or expected completion date."
    )


class CandidateProfile(BaseModel):
    """
    Represents the structured data extracted from a candidate's resume by the Resume Agent.
    """
    skills: Annotated[List[CleanStr], BeforeValidator(coerce_to_list)] = Field(
        default_factory=list, 
        description="List of parsed professional and engineering skills."
    )
    experience: Annotated[List[WorkExperience], BeforeValidator(coerce_to_list)] = Field(
        default_factory=list, 
        description="Chronological history of work and timeline experiences."
    )
    education: Annotated[List[EducationEntry], BeforeValidator(coerce_to_list)] = Field(
        default_factory=list, 
        description="Academic qualifications and degrees."
    )


class JobRequirements(BaseModel):
    """
    Represents the core structured requirements parsed from a job description by the JD Agent.
    """
    mandatory_proficiencies: Annotated[List[CleanStr], BeforeValidator(coerce_to_list)] = Field(
        default_factory=list, 
        description="Core technical proficiencies and required skills."
    )
    preferred_experiences: Annotated[List[CleanStr], BeforeValidator(coerce_to_list)] = Field(
        default_factory=list, 
        description="Preferred experiences or target background qualifications."
    )
    soft_requirements: Annotated[List[CleanStr], BeforeValidator(coerce_to_list)] = Field(
        default_factory=list, 
        description="Required soft skills, communication skills, or working styles."
    )
    seniority_bracket: Optional[CleanStr] = Field(
        default=None, 
        description="Implied seniority bracket for the role (e.g., 'Junior', 'Mid-Level', 'Senior', 'Lead')."
    )


class AnalysisReport(BaseModel):
    """
    Represents the comparative qualification report generated by the Qualification Agent.
    """
    comparative_analysis: Annotated[List[CleanStr], BeforeValidator(coerce_to_list)] = Field(
        default_factory=list,
        description="Step-by-step sequential reasoning comparing the candidate profile with the job description."
    )
    match_score: int = Field(
        ...,
        ge=0,
        le=100,
        description="Overall match percentage from 0 to 100."
    )
    skill_gaps: Annotated[List[CleanStr], BeforeValidator(coerce_to_list)] = Field(
        default_factory=list,
        description="Precise, non-subjective list of identified skill gaps."
    )


class OptimizationOutput(BaseModel):
    """
    Represents the optimized output suggestions and tailored resume contents generated by the Optimizer Agent.
    """
    tailored_resume_markdown: CleanStr = Field(
        ...,
        description="The optimized and tailored resume content in Markdown format, aligned with the job description."
    )
    cover_letter_markdown: CleanStr = Field(
        ...,
        description="The tailored cover letter in Markdown format, aligned with the job description."
    )
    skills_added: Annotated[List[CleanStr], BeforeValidator(coerce_to_list)] = Field(
        default_factory=list,
        description="Specific skills or keywords added/emphasized in the optimized profile."
    )
    experience_improvements: Annotated[List[CleanStr], BeforeValidator(coerce_to_list)] = Field(
        default_factory=list,
        description="Suggested improvement points or rewritten bullet points for the professional experience."
    )
